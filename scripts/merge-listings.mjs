/*
  data/listings/*.json → src/lib/data.listings.ts. Each file is a draft Product written by the
  approval job; the shop imports the generated module. Usage: node scripts/merge-listings.mjs [root]
*/
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const dir = path.join(root, 'data', 'listings')
let files = []
try { files = (await readdir(dir)).filter((f) => f.endsWith('.json')).sort() } catch { files = [] }
const items = []
for (const f of files) items.push(JSON.parse(await readFile(path.join(dir, f), 'utf8')))
const header = `/* Generated by scripts/merge-listings.mjs from data/listings/*.json. Do not edit by hand. */
import type { Product } from './data'

export const LISTINGS: Product[] = `
await mkdir(path.join(root, 'src', 'lib'), { recursive: true })
await writeFile(path.join(root, 'src', 'lib', 'data.listings.ts'), header + JSON.stringify(items, null, 2) + '\n')
console.log(`wrote src/lib/data.listings.ts: ${items.length} listings`)
