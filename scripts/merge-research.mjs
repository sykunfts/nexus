/*
  Merge verified research (research/expansion-*.json, schema in research/SCHEMA.md) into
  src/lib/data.expansion.ts. Prices convert to AUD at the currency.ts snapshot rates; the listed
  price and currency are kept in priceSource so the product page can show where it came from.
  Trend numbers are deterministic sample data until the trend worker runs.
  Usage: node scripts/merge-research.mjs
*/
import { readFile, writeFile, readdir } from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const RATES = { AUD: 1, USD: 0.66, EUR: 0.56, GBP: 0.49, JPY: 98 }   // units per AUD, same as src/lib/currency.ts
const LISTED_AT = '2026-10-03'

const VISUAL_OVERRIDE = {
  'marshall-emberton-iii': 'speaker', 'jbl-flip-7': 'speaker',
  'switchbot-lock-ultra': 'lock', 'aqara-smart-lock-u300': 'lock',
  'whoop-5-0': 'band', 'garmin-index-sleep-monitor': 'band',
  'withings-scanwatch-2': 'watch',
  'hyperice-normatec-elite': 'device', 'flipper-zero': 'device', 'raspberry-pi-5-desktop-kit-8gb': 'device', 'keychron-k2-he': 'device',
  'plaud-note-pro': 'pin', 'bee-pioneer': 'pin',
}
const LIGHT = ['white', 'silver', 'cream', 'ice', 'sand', 'grey', 'gray', 'satin']

const files = (await readdir(path.join(root, 'research'))).filter((f) => /^expansion-[a-z]\.json$/.test(f)).sort()
let items = []
for (const f of files) items = items.concat(JSON.parse(await readFile(path.join(root, 'research', f), 'utf8')))

const hash = (s) => { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0 } return h }
function sampleTrend(id) {
  const h = hash(id)
  const delta = 8 + (h % 85)
  const label = delta >= 50 ? 'Rising' : 'Steady'
  const base = 10 + (h % 20)
  const series = Array.from({ length: 8 }, (_, i) => Math.round(base + (delta / 100) * base * (i / 7) * 2 + ((h >> (i * 3)) % 4)))
  return { label, delta, series, source: 'Sample data until the trend worker runs' }
}
const r2 = (n) => Math.round(n * 100) / 100
const ensureVariants = (p) => (p.variants && p.variants.length ? p.variants : [{ id: 'standard', label: 'Standard', swatch: '#2b2b30' }])
  .map((v) => ({ ...v, hue: p.hue ?? 200, swatch: v.swatch || (LIGHT.some((w) => v.label.toLowerCase().includes(w)) ? '#e8e8ec' : '#1b1b1f') }))

const out = items.map((p) => {
  const rate = RATES[p.priceSource.currency]
  if (!rate) throw new Error(`${p.id}: unknown currency ${p.priceSource.currency}`)
  const price = p.priceSource.currency === 'AUD' ? r2(p.priceSource.amount) : Math.round(p.priceSource.amount / rate)
  const compareAt = p.compareAtSource ? Math.round(p.compareAtSource.amount / RATES[p.compareAtSource.currency]) : undefined
  const isNew = p.releasedAt && (Date.parse(LISTED_AT) - Date.parse(p.releasedAt)) / 86400000 <= 60
  const sources = [...new Set([...(p.sources ?? []), p.priceSource.at].filter(Boolean))]
  return {
    id: p.id, name: p.name, brand: p.brand, category: p.category, tagline: p.tagline,
    price, ...(compareAt && compareAt > price ? { compareAt } : {}),
    priceCheckedAt: p.checkedAt ?? LISTED_AT,
    priceSource: { amount: p.priceSource.amount, currency: p.priceSource.currency, at: p.priceSource.at },
    listedAt: LISTED_AT, ...(p.releasedAt ? { releasedAt: p.releasedAt } : {}), market: p.market ?? 'global',
    sources, ...(p.notes ? { notes: p.notes } : {}),
    rating: p.rating ? { value: p.rating.value, count: p.rating.count, at: p.rating.at } : null,
    stock: 'in',
    fulfil: p.origin === 'AU' ? { route: 'warehouse', origin: 'AU' } : { route: 'supplier', origin: p.origin },
    visual: VISUAL_OVERRIDE[p.id] ?? p.visual, hue: p.hue ?? 200,
    variants: ensureVariants(p), ...(p.options?.length ? { options: p.options } : {}),
    ...(isNew ? { badges: ['New'] } : {}),
    trend: sampleTrend(p.id),
    facts: p.facts ?? {}, ...(p.inBox?.length ? { inBox: p.inBox } : {}),
    specs: p.specs,
  }
})

const header = `/* Generated by scripts/merge-research.mjs from research/expansion-*.json on ${LISTED_AT}. Do not edit by hand. */
import type { Product } from './data'

export const EXPANSION: Omit<Product, 'photos'>[] = `
await writeFile(path.join(root, 'src', 'lib', 'data.expansion.ts'), header + JSON.stringify(out, null, 2) + '\n')
console.log(`wrote src/lib/data.expansion.ts: ${out.length} products from ${files.join(', ')}`)
